// 偵測一宮的十干克應格局（天盤干可能多於一個，逐一配對地盤干）
export function palaceGeju(palaceData) {
  const out = [];
  const tGans = palaceData.tianGan || [];
  const dGans = [palaceData.diGan, palaceData.diGanExtra].filter(Boolean);
  tGans.forEach((tg) => {
    dGans.forEach((dg) => {
      const hit = GAN_JU[`${tg}${dg}`];
      if (hit && hit[0]) out.push({ tian: tg, di: dg, name: hit[0], ji: hit[1], desc: hit[2] });
    });
  });
  return out;
}

// 全盤格局總覽：回傳 [{palace, tian, di, name, ji, desc}]
export function allGeju(result) {
  if (!result || !result.palaces) return [];
  const out = [];
  Object.values(result.palaces).forEach((p) => {
    palaceGeju(p).forEach((g) => out.push({ palace: p.palace, ...g }));
  });
  return out;
}
